/**
 * Generates src/kernel-version.ts from package.json.
 *
 * `FynMeshKernelCore.version` is read by anything that wants to know which
 * kernel it is running against, and it used to be a hand-written literal. That
 * drifted the moment a release bumped package.json without touching the class:
 * `@fynmesh/kernel@1.1.0` shipped reporting "1.0.0", and the shell demo's
 * status bar faithfully displayed the stale value.
 *
 * Generating the constant makes package.json the single source of truth. The
 * file is committed so `tsc`, editors and `vitest` (which run against src, not
 * the bundle) never depend on the build having run first; the build regenerates
 * it, so a release cannot leave it behind. kernel-version.test.ts asserts the
 * two agree, which turns a stale checkout into a failing test rather than a
 * wrong version in production.
 *
 * Kept out of the rollup/tsc pipeline deliberately: importing package.json
 * directly would need `rootDir` widened past src/ and a JSON plugin in the
 * rollup config, for one string.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkgPath = path.join(here, "../package.json");
const outPath = path.join(here, "../src/kernel-version.ts");

const { version } = JSON.parse(fs.readFileSync(pkgPath, "utf8"));

const contents = `// GENERATED by build/gen-version.mjs from package.json -- do not edit.
// Run \`fyn run gen-version\` (or any build) to refresh.

/** The version of \`@fynmesh/kernel\` this build was produced from. */
export const KERNEL_VERSION = ${JSON.stringify(version)};
`;

// Only write when it actually changes, so a no-op build does not churn the
// file's mtime and retrigger watchers.
const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
if (current === contents) {
  console.log(`src/kernel-version.ts already at ${version}`);
} else {
  fs.writeFileSync(outPath, contents);
  console.log(`src/kernel-version.ts written for ${version}`);
}
